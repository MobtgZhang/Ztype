/// 希腊字母与常见数学符号的 italic correction（近似值）
pub fn symbolItalicCorrection(cp: u21) f64 {
    if (cp >= 0x03B1 and cp <= 0x03C9) return 170;
    if (cp >= 0x0391 and cp <= 0x03A9) return 50;
    if (cp >= 0x2190 and cp <= 0x21FF) return 0;
    return 0;
}

/// 重音符号的字形高度（以 em 为单位）。Symbol 字体表只有宽度，
/// 这里按 TeX 的 accent 度量给出近似值，用于 accent 盒子的测量。
pub fn accentHeight(cp: u21) f64 {
    return switch (cp) {
        0x0300, 0x0301, 0x0306, 0x030C => 0.30, // `  ˘ ˇ
        0x0302, 0x0303, 0x20D7 => 0.28, // ˆ ˜ （可横向拉伸的宽重音）
        0x0307, 0x0308, 0x20DB => 0.22, // ¨
        0x0304, 0x0305, 0x0332 => 0.06, // （按规则线绘制）
        0x0338 => 0.55, // 斜杠
        else => 0.28,
    };
}

/// 重音字形底部相对文本基线的高度（em）：文本基线需下移这个量，
/// 才能让重音正好落在基座上方 clearance 处。
pub fn accentBaseline(cp: u21) f64 {
    if (accentHeight(cp) <= 0.1) return 0;
    return 0.45;
}

/// 是否是可以横向拉伸覆盖整个基座的宽重音
pub fn isWideAccent(cp: u21) bool {
    return switch (cp) {
        0x0302, 0x0303, 0x20D7, 0x0304, 0x0311, 0x20DB => true,
        else => false,
    };
}

/// base-14 字体无法绘制组合附点符号，这里映射到可打印的等价字符
pub fn accentRenderCp(cp: u21) u21 {
    return switch (cp) {
        0x0300 => 0x60, // `
        0x0301 => 0xB4, // 锐音符
        0x0302, 0x030C => 0x5E, // ^
        0x0303 => 0x7E, // ~
        0x0306 => 0xB8, // 短音符
        0x0307 => 0xB7, // 中点
        0x0308 => 0xA8, // 分音符
        0x0338 => 0x2F, // /
        0x20D7 => 0x2192, // Symbol 字体中的箭头
        else => cp,
    };
}
